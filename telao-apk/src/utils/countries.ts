/**
 * Converte o nome de um país para o código ISO 3166-1 Alpha-2.
 * Suporta nomes em inglês e português, case-insensitive.
 *
 * @param countryName Nome do país (ex: "Brazil", "South Africa", "England")
 * @returns Código ISO lowercase (ex: "br", "za", "gb-eng") ou null se não encontrado
 */
export function getCountryCode(countryName: string): string | null {
  if (!countryName) return null;

  const normalized = countryName.trim().toLowerCase();
  const code = COUNTRY_MAP[normalized];

  if (!code) {
    console.warn(`[Countries] País não mapeado: "${countryName}". Adicione ao helper.`);
  }

  return code || null;
}

/**
 * Verifica se um nome de país está mapeado.
 */
export function isCountryMapped(countryName: string): boolean {
  return getCountryCode(countryName) !== null;
}
